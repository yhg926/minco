def read_tsv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def write_tsv(path: Path, rows: Iterable[dict[str, object]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})


def markdown_escape(value: object) -> str:
    return str(value).replace("|", "\\|")


def write_markdown_plan(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="\n") as handle:
        handle.write("# Next Release-Grade Actions\n\n")
        handle.write(
            "Generated by `plan_next_release_grade_actions.py` from cached "
            "release-readiness, runtime, abundance-gap, scratch-headroom, and "
            "candidate-sample audits. It does not run profiling.\n\n"
        )
        handle.write("| Rank | Action | Type | Status | Reason |\n")
        handle.write("| --- | --- | --- | --- | --- |\n")
        for row in rows:
            handle.write(
                "| "
                f"{markdown_escape(row['rank'])} | "
                f"`{markdown_escape(row['action_id'])}` | "
                f"{markdown_escape(row['action_type'])} | "
                f"{markdown_escape(row['status'])} | "
                f"{markdown_escape(row['reason'])} |\n"
            )
        handle.write("\n## Evidence\n\n")
        for row in rows:
            handle.write(f"### {row['rank']}. `{row['action_id']}`\n\n")
            handle.write(f"- Status: `{row['status']}`\n")
            handle.write(f"- Artifact: `{row['artifact']}`\n")
            handle.write(f"- Evidence: `{row['evidence']}`\n\n")
        handle.write(
            "The machine-readable table is `results/next_release_grade_actions.tsv`; "
            "that file is intentionally under ignored experiment results.\n"
        )


def truthy(value: str) -> bool:
    return str(value).strip().lower() in {"true", "1", "yes"}


def read_optional_metric(path: Path, key_field: str = "metric") -> dict[str, dict[str, str]]:
    if not path.exists():
        return {}
    return {row[key_field]: row for row in read_tsv(path)}


def completed_hmp_samples(candidates: list[dict[str, str]]) -> list[int]:
    samples = {
        int(row["sample"])
        for row in candidates
        if row.get("sample", "").isdigit() and truthy(row.get("has_same_release_outputs", ""))
    }
    return sorted(samples)


def select_next_hmp_candidate(candidates: list[dict[str, str]]) -> dict[str, str]:
    unprofiled_release_grade = [
        row
        for row in candidates
        if truthy(row.get("release_truth_quality", ""))
        and not truthy(row.get("has_same_release_outputs", ""))
    ]
    if unprofiled_release_grade:
        unprofiled_release_grade.sort(
            key=lambda row: (
                -float(row["truth_mass_mapped_pct"]),
                -int(row["source_genomes_positive"]),
                int(row["sample"]),
            )
        )
        return unprofiled_release_grade[0]

    omitted_route_missing = [
        row
        for row in candidates
        if int(row["sample"]) in OMITTED_HMP_AIRSKIN_ROUTE_SAMPLES
        and not truthy(row.get("has_same_release_outputs", ""))
    ]
    omitted_route_missing.sort(
        key=lambda row: (
            not truthy(row.get("release_truth_quality", "")),
            -float(row["truth_mass_mapped_pct"]),
            -int(row["source_genomes_positive"]),
            int(row["sample"]),
        )
    )
    return omitted_route_missing[0] if omitted_route_missing else {}


